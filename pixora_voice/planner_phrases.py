"""Bounded, app-owned Speech-to-Phrase vocabulary. JSON is valid YAML."""
import json,re,tempfile,os,hashlib
from pathlib import Path
MARKER='# Generated by Pixora Voice. Do not edit.\n'

def vocabulary_signature(phrases,variables):
 def words(value):return ' '.join(re.findall(r'[a-z0-9]+',value.lower()))
 payload={'phrases':sorted(set(words(p) for p in phrases)), 'variables':sorted(set(words(re.sub(r'([a-z])([A-Z])',r'\1 \2',v)) for v in variables))}
 return hashlib.sha256(json.dumps(payload,sort_keys=True).encode()).hexdigest()

def write_phrase_if_changed(path, content, check_only=False):
 path=Path(path)
 if path.exists():
  previous=path.read_text(encoding='utf-8')
  if path.is_symlink() or not previous.startswith(MARKER):raise ValueError('A user-owned phrase file was preserved.')
  def canonical(value):
   if isinstance(value,dict):return {k:canonical(v) for k,v in value.items()}
   if isinstance(value,list):return sorted((canonical(v) for v in value),key=lambda v:json.dumps(v,sort_keys=True))
   return value
  try:
   if canonical(json.loads(previous.removeprefix(MARKER)))==canonical(json.loads(content.removeprefix(MARKER))):return False
  except ValueError:pass
 if not check_only:write_owned(path,content)
 return True

